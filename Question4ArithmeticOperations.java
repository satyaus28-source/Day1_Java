// Question 4: Write a Java program to print the results of the given operations.

public class Question4ArithmeticOperations {
    public static void main(String[] args) { // Java starts running here.
        System.out.println(-5 + 8 * 6); // Multiply before adding.
        System.out.println((55 + 9) % 9); // Add first, then find the remainder.
        System.out.println(20 + -3 * 5 / 8); // Multiply and divide before adding.
        System.out.println(5 + 15 / 3 * 2 - 8 % 3); // Find each term before adding and subtracting.
    }
}
