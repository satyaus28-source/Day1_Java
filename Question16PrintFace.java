// Question 16: Write a Java program to print a face.

public class Question16PrintFace {
    public static void main(String[] args) { // Java starts running here.
        System.out.println(" +\"\"\"\"\"+"); // Use \" to print a double quote.
        System.out.println("[| o o |]"); // Print the eyes.
        System.out.println(" |  ^  |"); // Print the nose.
        System.out.println(" | '-' |"); // Print the mouth.
        System.out.println(" +-----+"); // Print the bottom of the face.
    }
}
